def repo_root(arg=None):
    if arg:
        return os.path.abspath(os.path.expanduser(arg))
    return os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def now_ts():
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def valid_date(value):
    if not DATE_RE.match(value or ""):
        return False
    try:
        _date.fromisoformat(value)
    except ValueError:
        return False
    return True


def load(root):
    """Read the JSONL, tolerating blank lines. A bad line is fatal, loudly.

    Silently dropping an unparseable row would lose an event, which is the one
    thing this file exists to prevent.
    """
    path = os.path.join(root, JSONL)
    rows = []
    if not os.path.exists(path):
        return rows
    with open(path, encoding="utf-8") as f:
        for n, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            try:
                row = json.loads(line)
            except json.JSONDecodeError as e:
                sys.exit(f"{JSONL}:{n} is not valid JSON ({e}).\n"
                         f"Fix the line by hand — do not delete it.")
            if not isinstance(row, dict):
                sys.exit(f"{JSONL}:{n} is not a JSON object.\n"
                         f"Fix the line by hand — do not delete it.")
            rows.append(row)
    return rows


def normalise(row):
    out = {}
    for k in FIELDS:
        if k == "backfilled":
            out[k] = bool(row.get(k, False))
        elif k == "history":
            out[k] = list(row.get(k) or [])
        else:
            v = row.get(k, "")
            out[k] = v if v is not None else ""
    return out


def atomic_write(path, text):
    """Write the whole file, then swap it in. A crash mid-write leaves the old
    file intact rather than a truncated record."""
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, path)


def write_all(root, rows):
    text = "".join(json.dumps(normalise(r), ensure_ascii=False) + "\n"
                   for r in rows)
    atomic_write(os.path.join(root, JSONL), text)


def row_id(row):
    try:
        return int(row.get("id") or 0)
    except (TypeError, ValueError):
        return 0


def next_id(rows):
    return max((row_id(r) for r in rows), default=0) + 1


def by_id(rows):
    return {row_id(r): r for r in rows}


def esc(value):
    """Keep a pipe or a newline in a field from breaking the markdown table."""
    return str(value or "").replace("|", "\\|").replace("\n", " ").strip()


def party_labels(root):
    """Labels from the Register table in PARTIES.md, or None if there is no
    such file. Parsed loosely: the first cell of every table row under the
    `## Register` heading, minus the header and separator rows."""
    path = os.path.join(root, PARTIES)
    if not os.path.exists(path):
        return None
    labels, in_register = set(), False
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.startswith("#"):
                in_register = line.strip().lower().startswith("## register")
                continue
            if not (in_register and line.lstrip().startswith("|")):
                continue
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            label = cells[0] if cells else ""
            if not label or label.lower() == "label" or set(label) <= set("-: "):
                continue
            labels.add(label)
    return labels


