#!/usr/bin/env python3
"""log.py — append to, query, check and render the exchange log (rule R4).

    python3 05_tools/log.py add --date 2026-08-18 --dir in --party "ACME" \
        --type letter --doc "Notice of delay" --ref "ACME-L-0142" \
        --path 03_exchange/received/ACME/2026-08-18_notice-of-delay.pdf \
        --thread delay-claim --action open --due 2026-09-01
    python3 05_tools/log.py add --date 2026-08-25 --dir out --party "ACME" \
        --type letter --doc "Reply to notice of delay" --ref "T-0031" \
        --path 03_exchange/issued/ACME/L-0088.pdf --thread delay-claim --answers 12
    python3 05_tools/log.py add --date 2026-09-02 --dir out --party "ACME" \
        --type report --doc "Method statement" --rev C \
        --path 03_exchange/issued/ACME/MS-004-C.pdf --supersedes 15
    python3 05_tools/log.py query --action open            # what is owed, either way
    python3 05_tools/log.py query --party ACME --dir in --since 2026-01-01
    python3 05_tools/log.py set 41 --action closed
    python3 05_tools/log.py check                          # the log against the tree
    python3 05_tools/log.py render                         # rewrite LOG.md

On Windows use `py -3` in place of `python3`.

Why the log is two files
------------------------
`03_exchange/LOG.jsonl` is the record: one JSON object per line, one line per
event, in the order they were written. `03_exchange/LOG.md` is a rendered view
of it, regenerated by this script.

A contract that runs for two years produces thousands of these rows. A markdown
table stops being usable long before that — it cannot be filtered, sorted or
counted, and every hand-edit risks mangling a column. JSONL can be queried in
one pass, by this script or by an agent reading it directly, and it stays
diffable and human-legible in a text editor. The markdown view exists so the log
is still readable by someone with no tools at all.

Both files live in a frozen zone. They are exempt from R1's no-edit rule in
one specific way: rows are added, and a row's `status`, `action`, `due` and
`note` may be updated in place through `set` — which records every change in
the row's `history`. Nothing else about a row is ever rewritten. A row that was
wrong is corrected by a new row, with a note. Rendering preserves anything you
write in LOG.md outside the generated block.

What a row is
-------------
One row per **event**: a document arrived, or a document left. A revision that
was superseded keeps its row; the new revision gets its own. A transmittal
that brought thirty drawings can be one row whose `path` is the folder they
were filed in, or thirty rows if each drawing's revision has to be tracked —
the project decides, and the register (R11) is where a series is followed.

Fields
------
id          assigned on append, never reused; cite it as #12
date        ISO date of the EVENT — sent or received — never of typing it up.
            Required, and must be a real calendar date. If neither the document
            nor the user states it, the row waits: a guessed date is worse than
            no row, because it looks like a fact.
recorded    when the row was written (UTC), set by the script
backfilled  true when the row was written from the documents after the fact
            (--backfilled) rather than at the moment of the event. Permitted;
            marked, so it is never mistaken for a contemporaneous entry.
dir         in | out
party       who it came from or went to, by the label in PARTIES.md
type        letter | drawing | boq | report | po | vo | instruction | submittal |
            minutes | transmittal | invoice | programme | email | contract |
            amendment | notice | rfi | application | certificate | claim | other
            (open set — an unlisted type is accepted with a warning)
doc         what the document is, in words, or its title
ref         the document's own number, or how it arrived (`email (transcript)`)
rev         the sender's revision, not an internal one
thread      the topic or negotiation, matching a context md in datasets/
path        repo-relative path to the filed document, or to the folder holding a
            multi-file event. For an issued document, the PDF — its source sits
            beside it under the same stem (R10).
status      the state of the DOCUMENT: current | superseded by #n | withdrawn
action      what is OWED on it: (blank) | open | answered by #n | closed.
            On an `in` row `open` means we owe a reply; on an `out` row, they do.
due         ISO date the open action is due, if one is set
note        anything that does not fit a column
history     every change made by `set`: field, from, to, when

`status` and `action` are separate because they answer different questions. An
issued letter that asks something is `current` and `open` at once; when the
answer arrives it stays `current` and becomes `answered by #n`; when the next
revision goes out it becomes `superseded by #n` whether or not it was answered.
One column cannot hold both, and the log used to try.

What `add` refuses, and what it merely flags
--------------------------------------------
Refused (nothing is written): a date that is not a real calendar date; a
status or action outside the vocabulary; a path that is absolute or escapes
the repository; a path under 03_exchange/ whose received/issued folder does not
match --dir, or whose party folder does not match --party (direction and party
are lookups, R1 — the row and the tree must agree); a path that points at
nothing, unless --pending says the file is genuinely still on its way; a
--supersedes or --answers id that does not exist. All of it is checked before
anything is written, and the new row and the rows it changes are written in
one atomic replacement — a failed add leaves the log exactly as it was.

Flagged (written, with a warning): a type outside the usual list; a party
label not in PARTIES.md; superseding a row that is already superseded, or of a
different party; answering a row that is not open, or that is in the same
direction. Warnings are for the human; they never change what was written.

`check` reads the whole log against the tree and reports what does not add up:
duplicate ids, dangling #n references, paths that point at nothing, rows and
folders that disagree, party labels not in PARTIES.md, open actions past their
due date, and — the one that matters most — files in 03_exchange/received/,
03_exchange/issued/ or 01_contract/ that no row mentions. A row covers its
path, everything under it if the path is a folder, and any sibling under the
same stem — the source filed beside an issued PDF (R10). Run it at session
start; it is the log read by its gaps.

One writer at a time. The log is a file in a synced folder; two machines
appending at the same moment produce a sync-conflict copy, which the
session-start scan reports (CONFLICT?), and possibly a duplicated id, which
`check` reports. Neither is silent, and neither is worth a locking scheme.
"""

import argparse
import json
import os
import posixpath
import re
import sys
from datetime import date as _date, datetime, timezone

LOG_DIR = "03_exchange"
JSONL = os.path.join(LOG_DIR, "LOG.jsonl")
MARKDOWN = os.path.join(LOG_DIR, "LOG.md")
PARTIES = os.path.join("00_AI_context", "PARTIES.md")

EXCHANGE = "03_exchange/"
CONTRACT = "01_contract/"
# Zones in which every file is expected to have a row (R4). 02_basis/ is not
# one: reference material nobody sent has no direction and no party.
LOGGED_ZONES = ("03_exchange/received/", "03_exchange/issued/", CONTRACT)

BEGIN = "<!-- LOG:BEGIN — generated by 05_tools/log.py; edits here are lost -->"
END = "<!-- LOG:END -->"

FIELDS = ("id", "date", "recorded", "backfilled", "dir", "party", "type", "doc",
          "ref", "rev", "thread", "path", "status", "action", "due", "note",
          "history")
# Columns worth a place in the rendered table. The rest stay in the JSONL,
# where they are still queryable — a fourteen-column markdown table is
# unreadable. Status and action share one column in the view.
COLUMNS = (("date", "Date"), ("dir", "Dir"), ("party", "Party"),
           ("type", "Type"), ("doc", "Document"), ("rev", "Rev"),
           ("ref", "Ref"), ("thread", "Thread"))

DIRECTIONS = ("in", "out")
# Not a closed set — an unlisted type is accepted with a warning, because a
# real project always turns up a document class nobody anticipated.
KNOWN_TYPES = ("letter", "drawing", "boq", "report", "po", "vo", "instruction",
               "submittal", "minutes", "transmittal", "invoice", "programme",
               "email", "contract", "amendment", "notice", "rfi", "application",
               "certificate", "claim", "other")
STATUS_RE = re.compile(r"^(current|superseded by #\d+|withdrawn)$")
ACTION_RE = re.compile(r"^(|open|answered by #\d+|closed)$")
STATUS_HELP = "current | 'superseded by #n' | withdrawn"
ACTION_HELP = "open | 'answered by #n' | closed | '' (nothing owed)"
REF_RE = re.compile(r"#(\d+)")
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")

# Files the tree may contain beside the documents; `check` expects no row for
# these. Mirrors update_index.py's skip rules.
SKIP_PREFIXES = ("~", ".")
SKIP_SUFFIXES = (".tmp", ".partial", ".crdownload")
SKIP_NAMES = {"desktop.ini", "Thumbs.db"}


