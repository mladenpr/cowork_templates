def status_cell(r):
    text = esc(r.get("status"))
    action = esc(r.get("action"))
    if action:
        text += f" · {action}"
        if action == "open" and r.get("due"):
            text += f" (due {esc(r.get('due'))})"
    return text


def render_table(rows):
    if not rows:
        return ["_No entries yet._", ""]
    head = ["#"] + [label for _, label in COLUMNS] + ["Status"]
    out = ["| " + " | ".join(head) + " |",
           "|" + "|".join("---" for _ in head) + "|"]
    backfilled = False
    for r in rows:
        cells = [f"{r.get('id', '')}"]
        for key, _ in COLUMNS:
            cell = esc(r.get(key))
            if key == "date" and r.get("backfilled"):
                cell += " †"
                backfilled = True
            cells.append(cell)
        cells.append(status_cell(r))
        out.append("| " + " | ".join(cells) + " |")
    out.append("")
    if backfilled:
        out += ["† backfilled — written from the documents after the event, "
                "not at the time (R4).", ""]
    return out


def outstanding_lines(rows):
    def key(r):
        return (r.get("due") or "9999-99-99", r.get("date") or "", row_id(r))

    def line(r):
        due = f" — due {esc(r.get('due'))}" if r.get("due") else ""
        thread = f" ({esc(r.get('thread'))})" if r.get("thread") else ""
        return (f"- **#{r.get('id')}** {esc(r.get('date'))} "
                f"{esc(r.get('party'))}: {esc(r.get('doc'))}{thread}{due}")

    open_rows = [r for r in rows if (r.get("action") or "") == "open"]
    we_owe = sorted((r for r in open_rows if r.get("dir") == "in"), key=key)
    they_owe = sorted((r for r in open_rows if r.get("dir") == "out"), key=key)
    body = ["## Outstanding", ""]
    if not open_rows:
        body += ["Nothing open.", ""]
        return body, 0
    body += ["Events whose action is still `open` — what is owed, in either",
             "direction. This is the progress-meeting question, so it is",
             "derived rather than maintained. Run `log.py check` for what is",
             "past its due date.", ""]
    body += ["### We owe a reply", ""]
    body += [line(r) for r in we_owe] or ["- nothing"]
    body += ["", "### They owe a reply", ""]
    body += [line(r) for r in they_owe] or ["- nothing"]
    body.append("")
    return body, len(open_rows)


def render(root, quiet=False):
    """Rewrite the generated block of LOG.md, leaving the rest of it alone."""
    rows = sorted(load(root), key=lambda r: (r.get("date", ""), row_id(r)))
    body = [BEGIN, ""]
    body += [f"{len(rows)} event(s). Generated from `LOG.jsonl` by "
             f"`05_tools/log.py`. Add rows with `log.py add` — hand-editing "
             f"this table changes nothing, because the JSONL is the record.",
             ""]
    body += render_table(rows)
    lines, n_open = outstanding_lines(rows)
    body += lines
    body.append(END)

    path = os.path.join(root, MARKDOWN)
    existing = ""
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            existing = f.read()
    block = "\n".join(body)
    if BEGIN in existing and END in existing:
        pre = existing.split(BEGIN)[0]
        post = existing.split(END, 1)[1]
        text = pre + block + post
    else:
        # No markers: the file is a fresh template or was replaced. Keep
        # whatever prose is there and put the block at the end.
        text = (existing.rstrip() + "\n\n" + block + "\n") if existing else block + "\n"
    atomic_write(path, text)
    if not quiet:
        print(f"{MARKDOWN} rendered — {len(rows)} event(s), {n_open} open.")
    return 0


