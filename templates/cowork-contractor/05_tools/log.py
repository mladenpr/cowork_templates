def cmd_add(root, args):
    rows = load(root)
    problems, warnings, path = validate_add(root, args, rows)
    if problems:
        sys.exit("Cannot log this event — nothing was written:\n  "
                 + "\n  ".join(problems))
    ts = now_ts()
    row = {"id": next_id(rows), "date": args.date, "recorded": ts,
           "backfilled": bool(args.backfilled), "dir": args.dir,
           "party": args.party, "type": args.type, "doc": args.doc,
           "ref": args.ref, "rev": args.rev, "thread": args.thread,
           "path": path, "status": args.status, "action": args.action,
           "due": args.due, "note": args.note, "history": []}
    known = by_id(rows)
    changed = []
    if args.supersedes is not None:
        t = known[args.supersedes]
        apply_change(t, "status", f"superseded by #{row['id']}", ts)
        changed.append(f"#{args.supersedes} → superseded by #{row['id']}")
    if args.answers is not None:
        t = known[args.answers]
        apply_change(t, "action", f"answered by #{row['id']}", ts)
        changed.append(f"#{args.answers} → answered by #{row['id']}")
    rows.append(row)
    write_all(root, rows)          # one atomic write: the row and its effects
    for w in warnings:
        print(f"warning: {w}")
    print(f"Logged #{row['id']}: {row['date']} {row['dir']} {row['party']} — "
          f"{row['doc']}")
    for c in changed:
        print(f"  {c}")
    render(root, quiet=True)
    return 0


def apply_change(row, field, new, ts):
    old = row.get(field, "")
    if old == new:
        return False
    row.setdefault("history", []).append(
        {"field": field, "from": old, "to": new, "on": ts})
    row[field] = new
    return True


def cmd_set(root, args):
    """Update a row's status, action, due, note, or a pending path — the fields
    that legitimately change after the event. Every change is recorded in the
    row's history."""
    rows = load(root)
    known = by_id(rows)
    if args.id not in known:
        sys.exit(f"No event #{args.id} in {JSONL}.")
    row = known[args.id]
    problems, changes = [], []
    if args.status is not None:
        if not STATUS_RE.match(args.status):
            problems.append(f"--status must be {STATUS_HELP} — got "
                            f"'{args.status}'")
        problems += [f"--status cites {d}, which does not exist"
                     for d in dangling(args.status, known)]
        changes.append(("status", args.status))
    if args.action is not None:
        if not ACTION_RE.match(args.action):
            problems.append(f"--action must be {ACTION_HELP} — got "
                            f"'{args.action}'")
        problems += [f"--action cites {d}, which does not exist"
                     for d in dangling(args.action, known)]
        changes.append(("action", args.action))
    if args.due is not None:
        if args.due and not valid_date(args.due):
            problems.append(f"--due must be a real ISO date, got '{args.due}'")
        changes.append(("due", args.due))
    if args.path is not None:
        path = norm_path(args.path)
        if row.get("path"):
            problems.append(f"#{args.id} already has a path "
                            f"('{row['path']}'). A path is fixed once set; a "
                            f"row filed against the wrong file is corrected by "
                            f"a new row with a note.")
        elif not path:
            problems.append("--path is empty")
        else:
            problems += path_problems(root, path, row.get("dir"),
                                      row.get("party"))
            changes.append(("path", path))
    if args.note is not None:
        old = row.get("note") or ""
        changes.append(("note", f"{old} | {args.note}" if old else args.note))
    if problems:
        sys.exit("Cannot update #%d — nothing was written:\n  " % args.id
                 + "\n  ".join(problems))
    if not changes:
        sys.exit("Nothing to change: pass --status, --action, --due, --path "
                 "or --note.")
    ts = now_ts()
    applied = [f for f, v in changes if apply_change(row, f, v, ts)]
    if not applied:
        print(f"#{row['id']} unchanged — already as requested.")
        return 0
    write_all(root, rows)
    print(f"#{row['id']} → " + ", ".join(
        f"{f} '{row.get(f, '')}'" for f in applied))
    return render(root, quiet=True)


def matches(row, args, today):
    def eq(field, wanted):
        return wanted is None or (row.get(field) or "").lower() == wanted.lower()

    if not (eq("dir", args.dir) and eq("party", args.party)
            and eq("type", args.type) and eq("thread", args.thread)
            and eq("status", args.status) and eq("action", args.action)):
        return False
    if args.since and (row.get("date") or "") < args.since:
        return False
    if args.until and (row.get("date") or "") > args.until:
        return False
    if args.overdue and not ((row.get("action") or "") == "open"
                             and row.get("due") and row["due"] < today):
        return False
    if args.grep:
        blob = " ".join(str(row.get(k, "")) for k in FIELDS
                        if k != "history").lower()
        if args.grep.lower() not in blob:
            return False
    return True


def cmd_query(root, args):
    today = _date.today().isoformat()
    rows = sorted((r for r in load(root) if matches(r, args, today)),
                  key=lambda r: (r.get("date", ""), row_id(r)))
    if args.json:
        print(json.dumps(rows, ensure_ascii=False, indent=1))
        return 0
    if not rows:
        print("No matching events.")
        return 0
    for r in rows:
        print(f"#{r.get('id'):<4} {r.get('date', ''):<11} "
              f"{(r.get('dir') or ''):<4} {(r.get('party') or ''):<20.20} "
              f"{(r.get('type') or ''):<12.12} {(r.get('doc') or ''):<40.40} "
              f"{status_cell(r)}")
        if args.paths and r.get("path"):
            print(f"      {r['path']}")
    print(f"\n{len(rows)} event(s).")
    return 0


def tree_files(root, zone):
    base = os.path.join(root, zone)
    if not os.path.isdir(base):
        return
    for dirpath, dirnames, filenames in os.walk(base):
        dirnames[:] = sorted(d for d in dirnames if not d.startswith("."))
        for fn in sorted(filenames):
            if (fn.startswith(SKIP_PREFIXES) or fn in SKIP_NAMES
                    or fn.lower().endswith(SKIP_SUFFIXES)):
                continue
            full = os.path.join(dirpath, fn)
            if os.path.isfile(full):
                yield os.path.relpath(full, root).replace(os.sep, "/")


def cmd_check(root, args):
    """The log against the tree, and against itself."""
    rows = load(root)
    findings = []
    ids = [row_id(r) for r in rows]
    for d in sorted({i for i in ids if ids.count(i) > 1}):
        findings.append(("DUPLICATE ID", f"#{d} appears {ids.count(d)} times — "
                         f"two writers appended at once. Renumber the later "
                         f"one by hand and fix every citation of it."))
    known = set(ids)
    labels = party_labels(root)
    today = _date.today().isoformat()
    logged_paths, logged_dirs = set(), set()
    for r in rows:
        rid = f"#{r.get('id')}"
        if not valid_date(r.get("date")):
            findings.append(("BAD DATE", f"{rid} date '{r.get('date')}'"))
        if not STATUS_RE.match(r.get("status") or ""):
            findings.append(("BAD STATUS", f"{rid} status '{r.get('status')}'"))
        if not ACTION_RE.match(r.get("action") or ""):
            findings.append(("BAD ACTION", f"{rid} action '{r.get('action')}'"))
        for field in ("status", "action"):
            for d in dangling(r.get(field), known):
                findings.append(("DANGLING", f"{rid} {field} "
                                 f"'{r.get(field)}' cites {d}, which does not "
                                 f"exist"))
        p = r.get("path") or ""
        if p:
            full = os.path.join(root, p)
            if not os.path.exists(full):
                findings.append(("PATH MISSING", f"{rid} → {p}"))
            elif os.path.isdir(full):
                logged_dirs.add(p.rstrip("/") + "/")
            else:
                logged_paths.add(p)
            for problem in path_problems(root, p, r.get("dir"), r.get("party"),
                                         pending=True):
                findings.append(("ROW/TREE DISAGREE", f"{rid}: {problem}"))
        else:
            findings.append(("NO PATH", f"{rid} {r.get('date')} {r.get('dir')} "
                             f"{r.get('party')} — {r.get('doc')} (pending; "
                             f"fill with `set {r.get('id')} --path`)"))
        if labels is not None and (r.get("party") or "") not in labels:
            findings.append(("UNKNOWN PARTY", f"{rid} party '{r.get('party')}' "
                             f"is not a label in {PARTIES}"))
        if ((r.get("action") or "") == "open" and r.get("due")
                and r["due"] < today):
            findings.append(("OVERDUE", f"{rid} due {r['due']} — {r.get('dir')} "
                             f"{r.get('party')}: {r.get('doc')}"))
    # A logged path covers itself, everything under it if it is a folder, and
    # any sibling under the same stem — the source document filed beside an
    # issued PDF at the same revision (R10) is part of that one event.
    logged_stems = {os.path.splitext(p)[0] for p in logged_paths}
    for zone in LOGGED_ZONES:
        for rel in tree_files(root, zone):
            if (rel in logged_paths
                    or os.path.splitext(rel)[0] in logged_stems
                    or any(rel.startswith(d) for d in logged_dirs)):
                continue
            findings.append(("UNLOGGED", f"{rel} — in a logged zone with no "
                             f"row; ingest it (R3) or it is invisible to every "
                             f"query"))

    if not findings:
        print(f"Log is consistent — {len(rows)} event(s), every path resolves, "
              f"every logged zone accounted for.")
        return 0
    groups = {}
    for kind, text in findings:
        groups.setdefault(kind, []).append(text)
    for kind in groups:
        print(f"{kind} ({len(groups[kind])}):")
        for text in groups[kind]:
            print(f"  {text}")
        print()
    print(f"{len(findings)} finding(s). None of these are fixed by editing "
          f"LOG.jsonl by hand: file, log or `set` as each line says.")
    return 1


