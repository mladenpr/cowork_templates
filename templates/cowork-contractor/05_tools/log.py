    a.add_argument("--rev", default="", help="sender's revision")
    a.add_argument("--thread", default="", help="topic, matching a context md")
    a.add_argument("--status", default="current", help=f"document state: {STATUS_HELP}")
    a.add_argument("--action", default="", help=f"what is owed: {ACTION_HELP}")
    a.add_argument("--due", default="", help="ISO date the open action is due")
    a.add_argument("--note", default="", help="anything that fits no column")
    a.add_argument("--supersedes", type=int, metavar="ID",
                   help="mark an earlier event superseded by this one")
    a.add_argument("--answers", type=int, metavar="ID",
                   help="mark an earlier open event answered by this one")
    a.add_argument("--backfilled", action="store_true",
                   help="this row is written after the fact, from the documents")

    s = sub.add_parser("set", help="update status/action/due/note, or fill a pending path")
    s.add_argument("id", type=int)
    s.add_argument("--status", help=STATUS_HELP)
    s.add_argument("--action", help=ACTION_HELP)
