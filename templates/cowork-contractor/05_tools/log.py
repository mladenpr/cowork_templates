def norm_path(value):
    value = (value or "").strip().replace("\\", "/")
    if not value:
        return ""
    value = posixpath.normpath(value)
    return "" if value == "." else value


def path_problems(root, path, dir_, party, pending=False):
    """Why a path cannot go on a row with this direction and party.

    Direction and party are lookups (R1): received/ is theirs, issued/ is
    ours, and the party folder is the party's label. A row that says otherwise
    is wrong in exactly the way the tree exists to make impossible.
    """
    problems = []
    if (os.path.isabs(path) or re.match(r"^[A-Za-z]:", path)
            or path == ".." or path.startswith("../")):
        return [f"--path must be repo-relative and inside the repository — "
                f"got '{path}'"]
    if path.startswith(EXCHANGE):
        parts = path.split("/")
        if len(parts) < 4 or parts[1] not in ("received", "issued"):
            problems.append(f"a path under {EXCHANGE} must be "
                            f"{EXCHANGE}received/<party>/… or "
                            f"{EXCHANGE}issued/<party>/… — got '{path}'")
        else:
            want = "received" if dir_ == "in" else "issued"
            if parts[1] != want:
                problems.append(f"--dir {dir_} but the path is under "
                                f"{EXCHANGE}{parts[1]}/ — direction is the "
                                f"folder (R1); one of them is wrong")
            if parts[2] != party:
                problems.append(f"--party '{party}' but the path is under "
                                f"{EXCHANGE}{parts[1]}/{parts[2]}/ — the label "
                                f"and the folder must agree (PARTIES.md)")
    if not pending and not os.path.exists(os.path.join(root, path)):
        problems.append(f"no file at '{path}' — file it first (the procedure "
                        f"moves, then logs), or pass --pending and fill the "
                        f"path later with `set <id> --path`")
    return problems


def validate_add(root, args, rows):
    problems, warnings = [], []
    if not valid_date(args.date):
        problems.append(f"--date must be a real ISO date (YYYY-MM-DD), "
                        f"got '{args.date}'")
    if args.due and not valid_date(args.due):
        problems.append(f"--due must be a real ISO date, got '{args.due}'")
    if args.dir not in DIRECTIONS:
        problems.append(f"--dir must be one of {', '.join(DIRECTIONS)}")
    if not STATUS_RE.match(args.status):
        problems.append(f"--status must be {STATUS_HELP} — got '{args.status}'")
    if not ACTION_RE.match(args.action):
        problems.append(f"--action must be {ACTION_HELP} — got '{args.action}'")
    if args.due and args.action != "open":
        warnings.append("--due given without --action open — a due date on "
                        "nothing owed")
    if args.type and args.type not in KNOWN_TYPES:
        warnings.append(f"'{args.type}' is not one of the usual types "
                        f"({', '.join(KNOWN_TYPES)}) — recorded as given")

    path = norm_path(args.path)
    if path:
        problems += path_problems(root, path, args.dir, args.party, args.pending)
    elif not args.pending:
        problems.append("--path is required: a row that points at nothing is "
                        "the drift the log exists to prevent. Pass --pending "
                        "if the file genuinely has not landed yet, and fill it "
                        "with `set <id> --path`.")

    known = by_id(rows)
    for value, name in ((args.supersedes, "--supersedes"),
                        (args.answers, "--answers")):
        if value is not None and value not in known:
            problems.append(f"{name} #{value}: no such event")
    if args.supersedes in known:
        t = known[args.supersedes]
        if (t.get("status") or "").startswith("superseded"):
            warnings.append(f"#{args.supersedes} is already "
                            f"'{t.get('status')}' — superseding it again")
        if t.get("dir") != args.dir or t.get("party") != args.party:
            warnings.append(f"#{args.supersedes} is {t.get('dir')} "
                            f"{t.get('party')}; this row is {args.dir} "
                            f"{args.party} — a revision normally supersedes "
                            f"the same document to the same party")
    if args.answers in known:
        t = known[args.answers]
        if (t.get("action") or "") != "open":
            warnings.append(f"#{args.answers} is not open (action "
                            f"'{t.get('action') or ''}') — answering it anyway")
        if t.get("dir") == args.dir:
            warnings.append(f"#{args.answers} is also {args.dir} — an answer "
                            f"normally goes the other way")

    labels = party_labels(root)
    if labels is not None and args.party not in labels:
        warnings.append(f"'{args.party}' is not a label in {PARTIES} — add the "
                        f"party there first if it is new; labels are permanent")
    return problems, warnings, path


def dangling(value, known):
    return [f"#{m}" for m in REF_RE.findall(str(value or ""))
            if int(m) not in known]


