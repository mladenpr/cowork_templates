    a = sub.add_parser("add", help="append one event")
    a.add_argument("--date", required=True,
                   help="ISO date of the event itself — never guessed")
    a.add_argument("--dir", required=True, choices=DIRECTIONS,
                   help="in = received, out = issued")
    a.add_argument("--party", required=True, help="counterparty label, per PARTIES.md")
    a.add_argument("--doc", required=True, help="what the document is")
    a.add_argument("--path", default="",
                   help="repo-relative path to the filed document (or the folder "
                        "of a multi-file event); for an issued document, the PDF")
    a.add_argument("--pending", action="store_true",
                   help="the file has not landed yet: allow an empty or "
                        "not-yet-existing --path, to be filled with `set --path`")
